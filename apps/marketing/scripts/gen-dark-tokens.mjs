// Generates src/app/dark-tokens.generated.css from @mindnote/tokens/tokens.css.
//
// tokens.css ships its dark theme under a `.dark` class (the app toggles it with
// JS). The marketing site has no client JS, so it follows the OS setting instead:
// we copy the `.dark { … }` declarations into
// `@media (prefers-color-scheme: dark) { :root { … } }`.
// Generating (rather than hand-copying) keeps the two themes from drifting.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const tokensPath = require.resolve("@mindnote/tokens/tokens.css");
const css = readFileSync(tokensPath, "utf8");

const match = css.match(/(^|\n)\.dark\s*\{([\s\S]*?)\n\}/);
if (!match) {
  console.error("gen-dark-tokens: could not find a `.dark { … }` block in", tokensPath);
  process.exit(1);
}
const body = match[2]
  .split("\n")
  .map((l) => l.trim())
  .filter(Boolean)
  .map((l) => `    ${l}`)
  .join("\n");

const out = `/* GENERATED by scripts/gen-dark-tokens.mjs from @mindnote/tokens. Do not edit. */
@media (prefers-color-scheme: dark) {
  :root {
${body}
  }
}
`;
const target = join(here, "..", "src", "app", "dark-tokens.generated.css");
writeFileSync(target, out);
console.log("gen-dark-tokens: wrote", target);
